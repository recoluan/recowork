// Generate the website's complete chat kits from the CLI authority.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rw-chat-prompts-'));
try {
  const result = {};
  for (const template of ['idea-to-project', 'learning-engineering', 'web-design-standard']) {
    result[template] = {};
    for (const locale of ['zh', 'en']) {
      const dest = path.join(tmp, `${template}-${locale}`);
      execFileSync(process.execPath, [path.join(root, 'cli/recowork/bin/rw.js'), 'add', template, '--target', 'chat-mobile', '--locale', locale, dest]);
      const names = locale === 'zh' ? ['启动指令.md', '任务执行协议.md', '续接与迁移摘要.md'] : ['start-instruction.md', 'task-protocol.md', 'continuation-and-migration-summary.md'];
      result[template][locale] = names.map(name => fs.readFileSync(path.join(dest, name), 'utf8')).join('\n\n');
    }
  }
  const content = '// Generated by scripts/build-chat-prompts.cjs; do not edit.\nconst chatKits = '+JSON.stringify(result, null, 2)+';\n';
  const output = path.join(root, 'docs/chat-prompts.js');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== content) throw new Error('Website chat prompts are stale; run node scripts/build-chat-prompts.cjs');
  } else fs.writeFileSync(output, content);
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
